import fs from 'node:fs';
import path from 'node:path';

/**
 * Custom Vite PWA Plugin for FinLab
 * 
 * Features:
 * - Generates production-ready Service Worker with dynamic precache list of all Vite hashed assets.
 * - Protects all financial and authenticated endpoints from being cached.
 * - Serves sw.js during dev mode with correct headers.
 * - Handles offline fallback and app shell caching.
 */
export default function finlabPwaPlugin() {
  let viteConfig;

  return {
    name: 'finlab-pwa-plugin',
    configResolved(resolvedConfig) {
      viteConfig = resolvedConfig;
    },

    // Dev server middleware to serve sw.js if requested
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url === '/sw.js') {
          const swPath = path.resolve(viteConfig.root, 'public', 'sw.js');
          if (fs.existsSync(swPath)) {
            res.setHeader('Content-Type', 'application/javascript');
            res.setHeader('Service-Worker-Allowed', '/');
            res.setHeader('Cache-Control', 'no-cache, no-store, must-revalidate');
            return fs.createReadStream(swPath).pipe(res);
          }
        }
        next();
      });
    },

    // Generate production sw.js with actual bundle assets
    generateBundle(options, bundle) {
      const isProduction = viteConfig.command === 'build';
      if (!isProduction) return;

      const precacheAssets = new Set([
        '/',
        '/index.html',
        '/offline.html',
        '/manifest.webmanifest',
        '/manifest.json',
        '/favicon.svg',
        '/icons/icon-192x192.png',
        '/icons/icon-512x512.png',
        '/icons/icon-maskable-192x192.png',
        '/icons/icon-maskable-512x512.png',
        '/icons/apple-touch-icon.png',
        '/icons/icon.svg'
      ]);

      // Collect emitted chunks and assets
      for (const [fileName, fileInfo] of Object.entries(bundle)) {
        // Exclude map files or existing sw files
        if (fileName.endsWith('.map') || fileName === 'sw.js') continue;
        if (fileInfo.type === 'chunk' || fileInfo.type === 'asset') {
          precacheAssets.add(`/${fileName}`);
        }
      }

      const buildHash = Date.now().toString(36);
      const cacheName = `finlab-shell-v${buildHash}`;
      const precacheArrayJson = JSON.stringify(Array.from(precacheAssets), null, 2);

      const swContent = `/**
 * FinLab Production Service Worker
 * Generated by FinLab PWA Vite Plugin
 * Cache Name: ${cacheName}
 */

const CACHE_NAME = '${cacheName}';

const PRECACHE_ASSETS = ${precacheArrayJson};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_ASSETS).catch((err) => {
        console.warn('[FinLab SW] Precache warning:', err);
      });
    })
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key.startsWith('finlab-') && key !== CACHE_NAME) {
            console.log('[FinLab SW] Cleaned legacy cache:', key);
            return caches.delete(key);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

function isSensitiveOrApiRequest(url) {
  const pathname = url.pathname;
  return (
    pathname.startsWith('/api') ||
    url.port === '9003' ||
    url.hostname === 'accounts.google.com' ||
    url.hostname.includes('oauth') ||
    pathname.includes('/auth/') ||
    pathname.includes('/transactions') ||
    pathname.includes('/accounts') ||
    pathname.includes('/categories') ||
    pathname.includes('/budgets') ||
    pathname.includes('/recurring') ||
    pathname.includes('/savings') ||
    pathname.includes('/reports') ||
    pathname.includes('/settings') ||
    pathname.includes('/notifications') ||
    pathname.includes('/dashboard/summary')
  );
}

self.addEventListener('fetch', (event) => {
  const request = event.request;

  if (request.method !== 'GET') {
    return;
  }

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    return;
  }

  // STRICT PRIVACY: NEVER CACHE API ENDPOINTS OR FINANCIAL DATA
  if (isSensitiveOrApiRequest(url)) {
    event.respondWith(
      fetch(request).catch(() => {
        return new Response(
          JSON.stringify({
            success: false,
            message: 'You are currently offline. Financial data requires an active connection.',
            offline: true
          }),
          {
            status: 503,
            statusText: 'Service Unavailable',
            headers: { 'Content-Type': 'application/json' }
          }
        );
      })
    );
    return;
  }

  // NAVIGATION: SPA shell handling
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.status === 200) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(async () => {
          const cachedMatch = await caches.match(request);
          if (cachedMatch) return cachedMatch;

          const cachedShell = (await caches.match('/index.html')) || (await caches.match('/'));
          if (cachedShell) return cachedShell;

          const offlineFallback = await caches.match('/offline.html');
          if (offlineFallback) return offlineFallback;

          return new Response('Offline', { status: 503, statusText: 'Offline' });
        })
    );
    return;
  }

  // STATIC ASSETS: Vite chunks & Fonts
  const isViteAsset = url.pathname.startsWith('/assets/');
  const isFont = url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com';
  const isStaticFile = url.pathname.startsWith('/icons/') || url.pathname.endsWith('.svg') || url.pathname.endsWith('.png');

  if (isViteAsset || isFont || isStaticFile) {
    event.respondWith(
      caches.match(request).then((cached) => {
        if (cached) {
          if (!isViteAsset) {
            fetch(request).then((networkRes) => {
              if (networkRes && networkRes.status === 200) {
                const copy = networkRes.clone();
                caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
              }
            }).catch(() => {});
          }
          return cached;
        }

        return fetch(request).then((response) => {
          if (response && response.status === 200) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        }).catch(() => {
          return new Response('', { status: 408, statusText: 'Request Timeout' });
        });
      })
    );
    return;
  }

  // DEFAULT
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response && response.status === 200) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(() => caches.match(request))
  );
});
`;

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: swContent,
      });
    },
  };
}

